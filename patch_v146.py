#!/usr/bin/env python3
"""FS3 v146 - sharp warp vortices with a glow, the Sidhe.

    Vortex  both vortices come from new frame sheets built from Silvio's
            2048 pixel frames: 75 frames of 256 x 256 instead of 100 x 100,
            so the vortex of a destroyer is no longer blown up to twice its
            resolution. The frame size is read off the picture, so an old
            100 pixel sheet still works as well.
    Glow    behind every vortex its glow (WarpGlow01 / WarpGlow02), opening
            and closing with it.
    Sidhe   the scatter gun is called Sidhe, after the primary of Blue
            Planet: War in Heaven.

The four pictures are not in this patch; they go into images/ on the
server beside it: warp_img.webp, warp_knossos.webp, warp_glow.webp,
warp_glow_knossos.webp. build.sh stops if one of them is missing.

Needs v145. Edits src/00_head.html, src/20_render.js, src/40_world.js,
src/50_combat.js and src/70_ui.js in place, and writes the updated
fieldsim.js. Run assemble.py afterwards.
"""
import sys


def replace_once(text, old, new, label):
    n = text.count(old)
    if n != 1:
        sys.exit("Abbruch (%s): Suchtext %d-mal gefunden, erwartet einmal." % (label, n))
    return text.replace(old, new)


def load(p):
    return open(p, encoding="utf-8").read()


hd = load("src/00_head.html")
rd = load("src/20_render.js")
wo = load("src/40_world.js")
cb = load("src/50_combat.js")
ui = load("src/70_ui.js")

hd = replace_once(
    hd,
    '<img id="warp_knossos_img" src="@@FS3_ASSET:images/warp_knossos.webp@@" style="display:none">\n',
    '<img id="warp_knossos_img" src="@@FS3_ASSET:images/warp_knossos.webp@@" style="display:none">\n'
    '<img id="warp_glow_img" src="@@FS3_ASSET:images/warp_glow.webp@@" style="display:none">\n'
    '<img id="warp_glow_knossos_img" src="@@FS3_ASSET:images/warp_glow_knossos.webp@@" style="display:none">\n',
    "head imgs")

rd = replace_once(
    rd,
    "const WARP_COLS=9, WARP_CELL=100, WARP_FRAMES=75;\n",
    "// The size of one frame is read off the sheet: nine frames across, so\n"
    "// a 2304 pixel sheet has 256 pixel frames and the old one 100.\n"
    "const WARP_COLS=9, WARP_FRAMES=75;\n",
    "cell const")
rd = replace_once(
    rd,
    "const HULL_IMG=document.getElementById('hull_img');\n",
    "// The glow behind the vortex, one per kind.\n"
    "const WARP_GLOW_IMG=document.getElementById('warp_glow_img');\n"
    "const KNOSSOS_GLOW_IMG=document.getElementById('warp_glow_knossos_img');\n"
    "function imgReady(im){ return !!im && im.complete && im.naturalWidth>0; }\n"
    "// One vortex frame at the current transform, centred, WS across, with\n"
    "// its glow behind it. knossos: the turquoise one of the portal.\n"
    "const WARP_GLOW_SIZE = 2.0;     // glow width as a multiple of the vortex\n"
    "function drawWarpFrame(wF, WS, knossos){\n"
    "  const sheet = (knossos && imgReady(KNOSSOS_WARP_IMG)) ? KNOSSOS_WARP_IMG : WARP_IMG;\n"
    "  const glow  = (knossos && imgReady(KNOSSOS_GLOW_IMG)) ? KNOSSOS_GLOW_IMG : WARP_GLOW_IMG;\n"
    "  if(imgReady(glow)){\n"
    "    const G = WS*WARP_GLOW_SIZE, op = ctx.globalCompositeOperation;\n"
    "    ctx.globalCompositeOperation = 'lighter';\n"
    "    ctx.drawImage(glow, -G/2, -G/2, G, G);\n"
    "    ctx.globalCompositeOperation = op;\n"
    "  }\n"
    "  if(!imgReady(sheet)) return;\n"
    "  // A single picture rather than a sheet is drawn whole.\n"
    "  if(sheet.naturalWidth < WARP_COLS*40){ ctx.drawImage(sheet, -WS/2, -WS/2, WS, WS); return; }\n"
    "  const C = sheet.naturalWidth/WARP_COLS;\n"
    "  ctx.drawImage(sheet, (wF%WARP_COLS)*C, ((wF/WARP_COLS)|0)*C, C, C, -WS/2, -WS/2, WS, WS);\n"
    "}\n"
    "const HULL_IMG=document.getElementById('hull_img');\n",
    "drawWarpFrame")

wo = replace_once(
    wo,
    "    ctx.drawImage(WARP_IMG,\n"
    "      (wF%WARP_COLS)*WARP_CELL, ((wF/WARP_COLS)|0)*WARP_CELL,\n"
    "      WARP_CELL, WARP_CELL, -WS/2, -WS/2, WS, WS);\n",
    "    drawWarpFrame(wF, WS, false);\n",
    "bomb portals")
cb = replace_once(
    cb,
    "  ctx.drawImage(WARP_IMG,\n"
    "    (wF%WARP_COLS)*WARP_CELL, ((wF/WARP_COLS)|0)*WARP_CELL,\n"
    "    WARP_CELL, WARP_CELL, -WS/2, -WS/2, WS, WS);\n",
    "  drawWarpFrame(wF, WS, false);\n",
    "jump vortex")
ui = replace_once(
    ui,
    "          // Through the Knossos: the turquoise vortex.\n"
    "          if(e.portalWarp && knossosWarpOk()){\n"
    "            const _kw = KNOSSOS_WARP_IMG;\n"
    "            if(_kw.naturalWidth > WARP_CELL*1.5)\n"
    "              ctx.drawImage(_kw, (wF%WARP_COLS)*WARP_CELL, ((wF/WARP_COLS)|0)*WARP_CELL,\n"
    "                            WARP_CELL, WARP_CELL, -WS/2,-WS/2,WS,WS);\n"
    "            else ctx.drawImage(_kw, -WS/2,-WS/2,WS,WS);\n"
    "          } else\n"
    "          ctx.drawImage(WARP_IMG,\n"
    "            (wF%WARP_COLS)*WARP_CELL, ((wF/WARP_COLS)|0)*WARP_CELL,\n"
    "            WARP_CELL, WARP_CELL,\n"
    "            -WS/2,-WS/2,WS,WS);\n",
    "          // Through the Knossos: the turquoise vortex.\n"
    "          drawWarpFrame(wF, WS, !!e.portalWarp);\n",
    "ship vortex")

ui = replace_once(
    ui,
    "  {key:'scatter', name:'Streuschuss', unlock:14000,\n",
    "  // Named after the primary of Blue Planet: War in Heaven.\n"
    "  {key:'scatter', name:'Sidhe', unlock:14000,\n",
    "sidhe")

open("src/00_head.html", "w", encoding="utf-8").write(hd)
open("src/20_render.js", "w", encoding="utf-8").write(rd)
open("src/40_world.js", "w", encoding="utf-8").write(wo)
open("src/50_combat.js", "w", encoding="utf-8").write(cb)
open("src/70_ui.js", "w", encoding="utf-8").write(ui)

