"""FS3 v143 - fixes after the first test of missions 55 to 60, practice mode.

    Defectors   a capital ship that goes over and stays where she is keeps
                facing into the field instead of turning to the edge
                behind her (M56).
    Stiletto    what it puts into a subsystem is multiplied by 5.5: one bomb
                takes out a cruiser's system, two a corvette's (M57). The
                hull still only gets the ordinary bleed.
    M59         two allied fighter wings at the start, one more when the
                first enemy wing is down.
    Vortex      the turquoise Knossos vortex was an animated picture, which
                the game only shows as its first frame. This patch turns
                images/warp_knossos.webp into a frame sheet like the normal
                vortex (the original is kept as warp_knossos_anim.webp).
    Practice    works in every mode now, not only in the campaign: no lives
                are lost, and every ticket kind is topped up to 10 at the
                start of every wave. Switch it in the settings, or start
                with ?practice=1 in the address.

Needs v142. Edits src/30_waves.js, src/60_effects.js and src/70_ui.js in
place, converts images/warp_knossos.webp if it is still animated, and writes
the updated fieldsim.js and wpnsim.js. Run assemble.py afterwards.
"""
import os
import sys


def replace_once(text, old, new, label):
    n = text.count(old)
    if n != 1:
        sys.exit("Abbruch (%s): Suchtext %d-mal gefunden, erwartet einmal." % (label, n))
    return text.replace(old, new)


def load(p):
    return open(p, encoding="utf-8").read()


wv = load("src/30_waves.js")
fx = load("src/60_effects.js")
ui = load("src/70_ui.js")

# ══ Defectors keep facing into the field ════════════════════════════════
wv = replace_once(
    wv,
    "  if(a.defectRun){\n"
    "    e.escaping = a.defectRun;\n",
    "  // She stays where she was and fights from there. Turned the usual\n"
    "  // enemy way she would face the edge behind her; she faces into the\n"
    "  // field instead, and does not drive off to an enemy station.\n"
    "  if(!a.defectRun){\n"
    "    e.targetX = e.x;\n"
    "    e.flip = needsFlip(e.img, e.x > W*0.5);\n"
    "  }\n"
    "  if(a.defectRun){\n"
    "    e.escaping = a.defectRun;\n",
    "defect facing")

# ══ Stiletto ════════════════════════════════════════════════════════════
ui = replace_once(
    ui,
    "function subStrike(e, dmg, hx, hy){\n"
    "  if(!e.subs || !e.subs.length) return dmg;\n",
    "// What a subsystem warhead puts into the system it finds. At 1 a\n"
    "// Stiletto took five or six bombs per cruiser system, more than an\n"
    "// Ursa carries for a single ship. The hull only gets the usual bleed\n"
    "// of the plain warhead, so this is no way to kill a ship faster.\n"
    "const SUB_WARHEAD_MUL = 5.5;\n"
    "function subStrike(e, dmg, hx, hy){\n"
    "  if(!e.subs || !e.subs.length) return dmg;\n"
    "  return subStrikeRaw(e, dmg*SUB_WARHEAD_MUL, hx, hy) / SUB_WARHEAD_MUL;\n"
    "}\n"
    "function subStrikeRaw(e, dmg, hx, hy){\n",
    "stiletto mul")

# ══ M59: fighter support ════════════════════════════════════════════════
