# ══ The Knossos vortex as a frame sheet ═════════════════════════════════
# Same layout as images/warp_img.webp: 9 columns of 100 x 100, 75 frames.
# Only done on the server, where the picture is; skipped quietly elsewhere.
KW = "images/warp_knossos.webp"
if os.path.isfile(KW):
    try:
        from PIL import Image
        im = Image.open(KW)
        n = getattr(im, "n_frames", 1)
        if n > 1:
            COLS, CELL, FRAMES = 9, 100, 75
            rows = (FRAMES + COLS - 1) // COLS
            sheet = Image.new("RGBA", (COLS*CELL, rows*CELL), (0, 0, 0, 0))
            for i in range(FRAMES):
                im.seek(min(n-1, i*n//FRAMES))
                fr = im.convert("RGBA").resize((CELL, CELL), Image.LANCZOS)
                sheet.paste(fr, ((i % COLS)*CELL, (i // COLS)*CELL))
            os.replace(KW, "images/warp_knossos_anim.webp")
            sheet.save(KW, "WEBP", quality=90, method=6)
            print("Knossos-Wirbel: %d Einzelbilder in ein Raster umgebaut (Original: images/warp_knossos_anim.webp)" % n)
        else:
            print("Knossos-Wirbel: ist schon ein Raster (%dx%d), nichts zu tun" % im.size)
    except ImportError:
        print("Knossos-Wirbel: Pillow fehlt, nicht umgebaut")
else:
    print("Knossos-Wirbel: %s nicht gefunden, nicht umgebaut" % KW)

