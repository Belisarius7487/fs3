"""FS3 v141 - beams on top of the firing ship, no false losses at wave end.

    Beams   v140 put the whole ray under every hull, the firing ship's
            included. Now the ray still runs under the ships it hits, but
            the stretch across the firing ship's own hull is drawn again on
            top of her, so the beam leaves her visibly.
    Losses  an allied ship that jumped out at the end of a wave counted as
            destroyed ('vernichtet'), so M53 reported 'GTD ORION LOST' and
            'GTCV DEIMOS LOST' for two ships that had left safely. A jump
            out now counts as leaving.

Needs v140. Edits src/40_world.js and src/50_combat.js in place, and writes
the updated fieldsim.js. Run assemble.py afterwards.
"""
import sys


def replace_once(text, old, new, label):
    n = text.count(old)
    if n != 1:
        sys.exit("Abbruch (%s): Suchtext %d-mal gefunden, erwartet einmal." % (label, n))
    return text.replace(old, new)


def load(p):
    return open(p, encoding="utf-8").read()


wo = load("src/40_world.js")
cb = load("src/50_combat.js")

# ══ Beams: the firing ship's own stretch on top of her ═════════════════
cb = replace_once(
    cb,
    "function drawBeamRays(e) {\n"
    "  if(!e.beams) return;\n"
    "  for(const b of e.beams) {\n"
    "    if(b.state!=='firing') continue;\n"
    "    const col=beamCol(e.faction, b.large);\n"
    "    const ang = b.type==='slash' ? b.curAngle : b.angle;\n"
    "    const mpF=mountPos(e,b);\n"
    "    const len=2000;\n",
    "// own: only the stretch from the mount to the edge of the firing ship's\n"
    "// own hull. That part is drawn again on top of her, so the beam leaves\n"
    "// the ship that fires it instead of disappearing under her.\n"
    "function drawBeamRays(e, own) {\n"
    "  if(!e.beams) return;\n"
    "  for(const b of e.beams) {\n"
    "    if(b.state!=='firing') continue;\n"
    "    const col=beamCol(e.faction, b.large);\n"
    "    const ang = b.type==='slash' ? b.curAngle : b.angle;\n"
    "    const mpF=mountPos(e,b);\n"
    "    const len = own ? ownHullRun(e, mpF.x, mpF.y, ang) : 2000;\n"
    "    if(len <= 0) continue;\n",
    "rays own")
cb = replace_once(
    cb,
    "// Charge glow and muzzle orb, on top of the firing ship. The ray is\n"
    "// drawn separately, under the hulls, by drawBeamRays().\n"
    "function drawBeams(e) {\n"
    "  if(!e.beams) return;\n",
    "// How far a ray from (x,y) at angle a runs before it leaves the box of\n"
    "// ship e.\n"
    "function ownHullRun(e, x, y, a){\n"
    "  const img = IMGS[e.img];\n"
    "  if(!img) return 0;\n"
    "  const hw = img.width*e.sc/2, hh = img.height*e.sc/2;\n"
    "  const c = Math.cos(a), s = Math.sin(a);\n"
    "  let t = Infinity;\n"
    "  if(c > 1e-6)  t = Math.min(t, (e.x+hw - x)/c);\n"
    "  if(c < -1e-6) t = Math.min(t, (e.x-hw - x)/c);\n"
    "  if(s > 1e-6)  t = Math.min(t, (e.y+hh - y)/s);\n"
    "  if(s < -1e-6) t = Math.min(t, (e.y-hh - y)/s);\n"
    "  return (t === Infinity) ? 0 : Math.max(0, t);\n"
    "}\n"
    "\n"
    "// Charge glow and muzzle orb, on top of the firing ship, together with\n"
    "// the stretch of the ray across her own hull. The rest of the ray is\n"
    "// drawn under all hulls by drawBeamRays(e) before the ships.\n"
    "function drawBeams(e) {\n"
    "  if(!e.beams) return;\n"
    "  drawBeamRays(e, true);\n",
    "drawBeams own stretch")

# ══ Leaving at the end of the wave is not being destroyed ══════════════
wo = replace_once(
    wo,
    "      if(a.warpOut <= 0){ if(a.guard) guardGone = true; allies.splice(i,1); }\n",
    "      // Jumped out: she left. Without this 'vernichtet' read her as\n"
    "      // destroyed the moment she was gone.\n"
    "      if(a.warpOut <= 0){ if(a.uid) EV_LEFT[a.uid] = true;\n"
    "                          if(a.guard) guardGone = true; allies.splice(i,1); }\n",
    "ally jump is leaving")

open("src/40_world.js", "w", encoding="utf-8").write(wo)
open("src/50_combat.js", "w", encoding="utf-8").write(cb)

