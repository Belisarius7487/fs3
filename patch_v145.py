#!/usr/bin/env python3
"""FS3 v145 - practice log: lives, calls and refits counted right.

    Lives   every life picked up is counted, also at the maximum of 20
            lives, where it adds nothing. In practice mode the lives are
            not lost, so the counter sat at 20 from wave 31 on and the log
            showed no pickups at all. The log now says how many of them
            came at the maximum.
    Calls   a support call is logged as 'called GTD ORION' with the
            ticket it cost.
    Refits  turning tickets into a bigger one is logged as 'refined 4
            cruiser -> 1 corvette' and no longer counts as tickets used
            and earned.

Nothing in the game itself changes. Needs v144. Edits src/40_world.js and
src/70_ui.js in place, and writes the updated fieldsim.js and callsim.js.
Run assemble.py afterwards.
"""
import sys


def replace_once(text, old, new, label):
    n = text.count(old)
    if n != 1:
        sys.exit("Abbruch (%s): Suchtext %d-mal gefunden, erwartet einmal." % (label, n))
    return text.replace(old, new)


def load(p):
    return open(p, encoding="utf-8").read()


wo = load("src/40_world.js")
ui = load("src/70_ui.js")

# ══ Lives: counted at the pickup, not from the counter ══════════════════
wo = replace_once(
    wo,
    "        } else if(it.kind==='life'){\n"
    "          barPulse('lives', lives >= LIVES_MAX);\n",
    "        } else if(it.kind==='life'){\n"
    "          plogPick('life', lives >= LIVES_MAX);\n"
    "          barPulse('lives', lives >= LIVES_MAX);\n",
    "life pickup")
ui = replace_once(
    ui,
    "function plogPick(kind){\n"
    "  if(!PL) return;\n"
    "  if(kind==='repair'){ PL.picked.repair = (PL.picked.repair||0) + 1; plogEvent('repair picked up', 'good'); }\n"
    "}\n",
    "// full: the pickup changed nothing (lives already at their maximum).\n"
    "function plogPick(kind, full){\n"
    "  if(!PL) return;\n"
    "  if(kind==='repair'){ PL.picked.repair = (PL.picked.repair||0) + 1; plogEvent('repair picked up', 'good'); }\n"
    "  if(kind==='life'){\n"
    "    PL.picked.life = (PL.picked.life||0) + 1;\n"
    "    if(full) PL.picked.lifeFull = (PL.picked.lifeFull||0) + 1;\n"
    "    plogEvent(full ? 'life picked up (already at maximum)' : 'life picked up', 'good');\n"
    "  }\n"
    "}\n"
    "// A support call, with what it cost.\n"
    "function plogCall(a, kind){\n"
    "  if(!PL || !a) return;\n"
    "  PL.calls.push(plogName(a));\n"
    "  PL.tUsed[kind] = (PL.tUsed[kind]||0) + 1;\n"
    "  plogEvent('called '+plogName(a)+' (-1 '+kind+' ticket)', 'info');\n"
    "  PL._tickets = Object.assign({}, tickets);\n"
    "}\n"
    "// Tickets turned into a bigger one: neither used nor earned.\n"
    "function plogRefine(kind, n, up){\n"
    "  if(!PL) return;\n"
    "  PL.refined.push(n+' '+kind+' -> 1 '+up);\n"
    "  plogEvent('refined '+n+' '+kind+' -> 1 '+up, 'info');\n"
    "  PL._tickets = Object.assign({}, tickets);\n"
    "}\n",
    "plogPick life")
ui = replace_once(
    ui,
    "  if(lives > PL._lives){ PL.picked.life = (PL.picked.life||0) + (lives-PL._lives); plogEvent('life picked up', 'good'); }\n",
    "",
    "no lives diff")
ui = replace_once(
    ui,
    "        secFired:0, rearms:0, bolts:0, hits:0, allyLost:0, capLost:[], saved:0, lost:0, escaped:0,\n",
    "        secFired:0, rearms:0, bolts:0, hits:0, allyLost:0, capLost:[], saved:0, lost:0, escaped:0,\n"
    "        calls:[], refined:[],\n",
    "record fields")

# ══ Calls and refits ════════════════════════════════════════════════════
wo = replace_once(
    wo,
    "  tickets[allyTicket(id)]--;\n"
    "  STATS.escortsCalled++;\n",
    "  tickets[allyTicket(id)]--;\n"
    "  STATS.escortsCalled++;\n"
    "  plogCall(a, allyTicket(id));\n",
    "call hook")
wo = replace_once(
    wo,
    "  tickets[up] = (tickets[up]||0) + 1;\n",
    "  tickets[up] = (tickets[up]||0) + 1;\n"
    "  plogRefine(kind, REFINE_COST, up);\n",
    "refine hook")

# ══ In the text and the table ═══════════════════════════════════════════
ui = replace_once(
    ui,
    "    L.push('  picked up: lives '+(r.picked.life||0)+', repairs '+(r.picked.repair||0));\n"
    "    L.push('  tickets in '+JSON.stringify(r.tGot)+', out '+JSON.stringify(r.tUsed));\n",
    "    L.push('  picked up: lives '+(r.picked.life||0)+\n"
    "           (r.picked.lifeFull ? ' ('+r.picked.lifeFull+' at the maximum)' : '')+\n"
    "           ', repairs '+(r.picked.repair||0));\n"
    "    L.push('  tickets in '+JSON.stringify(r.tGot)+', out '+JSON.stringify(r.tUsed)+\n"
    "           (r.calls.length ? '  calls ['+r.calls.join(', ')+']' : '')+\n"
    "           (r.refined.length ? '  refined ['+r.refined.join(', ')+']' : ''));\n",
    "text lines")
ui = replace_once(
    ui,
    "      'tickets in '+(Object.keys(r.tGot).map(x=>x+' '+r.tGot[x]).join(', ')||'-')+\n"
    "        ', out '+(Object.keys(r.tUsed).map(x=>x+' '+r.tUsed[x]).join(', ')||'-'),\n",
    "      'tickets in '+(Object.keys(r.tGot).map(x=>x+' '+r.tGot[x]).join(', ')||'-')+\n"
    "        ', out '+(Object.keys(r.tUsed).map(x=>x+' '+r.tUsed[x]).join(', ')||'-')+\n"
    "        (r.refined.length ? ', refined '+r.refined.length+'x' : ''),\n"
    "      'lives picked up '+(r.picked.life||0)+(r.picked.lifeFull ? ' ('+r.picked.lifeFull+' at max)' : '')+\n"
    "        ', repairs '+(r.picked.repair||0)+', calls '+(r.calls.join(', ')||'-'),\n",
    "table lines")

open("src/40_world.js", "w", encoding="utf-8").write(wo)
open("src/70_ui.js", "w", encoding="utf-8").write(ui)

